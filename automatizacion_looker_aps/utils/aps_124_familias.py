from openpyxl.styles.builtins import percent


def main():
    ruta = r"C:\Users\Esteban Getial\OneDrive\Desktop\APS124CCFP20260629NI000900091143.txt"
    ruta_salida = r"C:\Users\Esteban Getial\OneDrive\Desktop\APS124CCFP20260629NI000900091143_CORREGIDO.txt"

    with open(ruta, "r", encoding="utf-8") as f:
        lineas = f.readlines()

    familias = []
    personas = []

    # 1. Separar registros tipo 2 y tipo 3
    for linea in lineas:
        partes = linea.strip().split("|")
        if partes[0] == "2":
            familias.append(partes)
        elif partes[0] == "3":
            personas.append(partes)

    # Convertimos a set (conjunto) para que las búsquedas sean ultrarrápidas
    personas_con_familia = {persona[-2] for persona in personas}

    ids_familia_a_borrar_en_personas = set()
    familias_filtradas = []

    # 2. Filtrar Familias (Sin modificar la lista original en caliente)
    for familia in familias:
        # Condición 1: T26 y MT03
        if familia[6] == "T26" and familia[7] == "MT03":
            ids_familia_a_borrar_en_personas.add(familia[-1])
            continue  # Al hacer continue, NO se agrega a familias_filtradas (se borra)

        # Condición 2: T45 y MT04
        if familia[6] == "T45" and familia[7] == "MT04":
            ids_familia_a_borrar_en_personas.add(familia[-1])
            continue

            # Condición 3: Validar huérfanos del tipo 2 sin hijos en tipo 3
        if familia[-1] not in personas_con_familia:
            continue

            # Si pasa todos los filtros, se conserva la familia
        familias_filtradas.append(familia)

    # 3. Filtrar Personas (Evitando el salto de registros)
    personas_filtradas = [
        persona for persona in personas
        if persona[-2] not in ids_familia_a_borrar_en_personas
    ]

    # 4. Volver a formatear y consolidar
    consolidado = []
    for familia in familias_filtradas:
        consolidado.append("|".join(familia) + "\n")

    for persona in personas_filtradas:
        consolidado.append("|".join(persona) + "\n")

    # Guardar en el nuevo archivo
    with open(ruta_salida, "w", encoding="utf-8") as f:
        f.writelines(consolidado)

    print(f"Proceso terminado. Familias conservadas: {len(familias_filtradas)}")


if __name__ == "__main__":
    main()



